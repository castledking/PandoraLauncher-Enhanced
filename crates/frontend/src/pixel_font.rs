fn glyph(character: char) -> &'static [&'static str; 8] {
    let find = |wanted: char| GLYPHS.iter().find(|(c, _)| *c == wanted).map(|(_, rows)| rows);
    find(character).or_else(|| find('?')).unwrap()
}

fn glyph_width(rows: &[&str; 8]) -> u32 {
    rows[0].len() as u32
}

/// `text` as a nameplate: white pixel text on the game's translucent black backing.
pub fn render_nameplate(text: &str) -> RgbaImage {
    let glyphs: Vec<_> = text.chars().map(glyph).collect();
    let text_width = glyphs.iter().map(|rows| glyph_width(rows)).sum::<u32>()
        + GLYPH_SPACING * glyphs.len().saturating_sub(1) as u32;

    let mut image = RgbaImage::from_pixel(text_width + PADDING * 2, GLYPH_HEIGHT + PADDING * 2, BACKING);
    let mut x = PADDING;
    for rows in glyphs {
        for (y, row) in rows.iter().enumerate() {
            for (dx, pixel) in row.bytes().enumerate() {
                if pixel == b'#' {
                    image.put_pixel(x + dx as u32, PADDING + y as u32, TEXT);
                }
            }
        }
        x += glyph_width(rows) + GLYPH_SPACING;
    }
    image
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_a_tidy_rectangle() {
        for (character, rows) in GLYPHS {
            let width = rows[0].len();
            assert!(width > 0, "{character:?} has no width");
            for row in rows {
                assert_eq!(row.len(), width, "{character:?} has ragged rows");
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "{character:?} has a stray character");
            }
        }
    }

    #[test]
    fn a_username_has_a_glyph_for_every_character() {
        for character in ('a'..='z').chain('A'..='Z').chain('0'..='9').chain(['_']) {
            assert!(GLYPHS.iter().any(|(c, _)| *c == character), "no glyph for {character:?}");
        }
    }

    #[test]
    fn the_plate_fits_the_text_with_a_pixel_around_it() {
        // "ab" is two five-wide glyphs with one pixel between them
        let image = render_nameplate("ab");
        assert_eq!((image.width(), image.height()), (5 + 1 + 5 + 2, 8 + 2));
        assert_eq!(*image.get_pixel(0, 0), BACKING);
    }

    #[test]
    fn unknown_characters_fall_back_to_a_question_mark() {
        assert_eq!(render_nameplate("é"), render_nameplate("?"));
    }

    #[test]
    fn descenders_reach_below_the_baseline() {
        let image = render_nameplate("g");
        let descender_row = PADDING + GLYPH_HEIGHT - 1;
        assert!((0..image.width()).any(|x| *image.get_pixel(x, descender_row) == TEXT));
        let image = render_nameplate("a");
        assert!((0..image.width()).all(|x| *image.get_pixel(x, descender_row) == BACKING));
    }
}
